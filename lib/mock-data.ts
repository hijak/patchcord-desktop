import type { IRCServer, IRCChannel, IRCMessage, IRCUser, MessageType } from './types'

let msgIdCounter = 0
function msgId() {
  return `msg-${++msgIdCounter}`
}

function makeMsg(
  channelId: string,
  serverId: string,
  type: MessageType,
  nickname: string,
  content: string,
  minutesAgo: number,
  isHighlight = false
): IRCMessage {
  return {
    id: msgId(),
    channelId,
    serverId,
    type,
    nickname,
    content,
    timestamp: new Date(Date.now() - minutesAgo * 60000),
    isHighlight,
  }
}

