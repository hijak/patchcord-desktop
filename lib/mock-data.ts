// --- Build Channels ---
function buildChannel(
  id: string,
  serverId: string,
  name: string,
  topic: string,
  messages: IRCMessage[],
  users: IRCUser[],
  isDM = false,
  unread = 0,
  mentions = 0
): IRCChannel {
  return {
    id,
    serverId,
    name,
    topic,
    topicSetBy: isDM ? undefined : users[0]?.nickname,
    messages,
    users: isDM ? [] : users,
    unreadCount: unread,
    mentionCount: mentions,
    isDirectMessage: isDM,
    joined: true,
    showJoinPart: true,
    modes: isDM ? '' : '+nst',
  }
}

